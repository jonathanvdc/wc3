use super::super::ClothColliderId;
use super::{EffectKind, LumpKind, Settings};
use crate::model::semantic::MaterialSlotId;
use crate::model::semantic::{Error, Id, MeshId, NodeId, Scope, Values};
use std::borrow::Cow;
/// Identity domain for independently authored soft bodies.
pub enum SoftBodyObject {}
/// Soft body belonging to its actual simulation domain.
pub type SoftBodyId = Id<SoftBodyObject>;
/// Identity domain for one soft body's deformation effects.
pub enum SoftEffectObject {}
/// Effect belonging to its actual soft body.
pub type SoftEffectId = Id<SoftEffectObject>;
/// Identity domain for one soft body's pivots.
pub enum SoftLumpObject {}
/// Deformation pivot belonging to its actual soft body.
pub type SoftLumpId = Id<SoftLumpObject>;
/// Identity domain for one soft body's rigid mesh portions.
pub enum RiderObject {}
/// Rigid mesh portion belonging to its actual soft body.
pub type RiderId = Id<RiderObject>;
/// Mesh and optional material restriction selecting a body portion.
#[derive(Clone, Debug)]
pub struct SoftPart {
    /// Geometry whose vertices participate.
    pub mesh: MeshId,
    /// Appearance-slot restriction; absence includes the whole mesh.
    pub material: Option<MaterialSlotId>,
}
/// A point on a mesh surface and its surrounding influence radius.
#[derive(Clone, Debug)]
pub struct SurfacePoint {
    /// Geometry carrying the attachment.
    pub mesh: MeshId,
    /// Polygon ordinal; coordinates select its first triangle.
    pub face: u32,
    /// Barycentric coordinates within the selected triangle.
    pub weights: [f32; 3],
    /// Influence radius, with zero selecting a point.
    pub radius: f32,
}
/// An independently selectable effect and all its retained authored settings.
#[derive(Clone, Debug)]
pub struct SoftEffect<'a> {
    /// Display name of this effect.
    pub name: Cow<'a, str>,
    /// Settings family currently selected for evaluation.
    pub kind: EffectKind,
    /// Allows the effect to contribute.
    pub enabled: bool,
    /// Baseline contribution before an animation declaration overrides it.
    pub amount: f32,
    /// Applies influence throughout the body.
    pub everywhere: bool,
    /// Permits the effect to excite jiggle motion.
    pub drives_jiggle: bool,
    /// Seed used for reproducible random choices.
    pub seed: u32,
    /// Surface location and radius anchoring this effect.
    pub place: Option<SurfacePoint>,
    /// Independently authored settings remain available when the selected family changes.
    pub settings: Settings<'a>,
}
/// A bind-time deformation pivot with hierarchy and effect associations.
#[derive(Clone, Debug)]
pub struct SoftLump {
    /// Surface, bone, or copied-bone behavior.
    pub kind: LumpKind,
    /// Surface anchor or selected bone pivot at the bind.
    pub anchor: [f32; 3],
    /// Model-space pivot at the bind.
    pub rest: [f32; 3],
    /// Approximate thickness beneath the pivot.
    pub depth: f32,
    /// Clearance from interior geometry, with zero requesting none.
    pub clear: f32,
    /// Hierarchy frame carrying the deformation pivot.
    pub carrier: Option<NodeId>,
    /// Hierarchy node represented or copied by the pivot.
    pub node: Option<NodeId>,
    /// Actual effect responsible for selecting this pivot.
    pub effect: Option<SoftEffectId>,
    /// Actual rigid mesh portion carried by this pivot.
    pub rider: Option<RiderId>,
    /// Permits jiggle to displace this pivot.
    pub swings: bool,
    /// Prevents scale deformation of this rigid rider pivot.
    pub rigid: bool,
}
/// A checked deformation definition containing its actual effects, pivots, and mesh portions.
#[derive(Clone, Debug)]
pub struct SoftBody<'a> {
    scope: Scope,
    effects: Vec<(SoftEffectId, SoftEffect<'a>)>,
    lumps: Vec<(SoftLumpId, SoftLump)>,
    riders: Vec<(RiderId, SoftPart)>,
    /// Display name.
    pub name: Cow<'a, str>,
    /// Geometry participating in deformation.
    pub meshes: Values<'a, MeshId>,
    /// Requested surface-pivot count before effect attachments add pivots.
    pub detail: u32,
    /// Copies participating bones even when they are not shared elsewhere.
    pub copy_all: bool,
    /// Retains bones with descendants as rotational chain elements.
    pub chains_as_they_are: bool,
    /// Interior geometry whose separation should be maintained.
    pub inside: Values<'a, SoftPart>,
    /// Spatial blending relative to the body's size.
    pub blend: f32,
    /// Maximum deformation influence count.
    pub influences: u8,
    /// Uses equal-share groups for classic skinning.
    pub equal_shares: bool,
    /// Contact capsules participating in the response.
    pub colliders: Vec<ClothColliderId>,
    /// Geometry generated by dripping, when present.
    pub drips: Option<MeshId>,
}
impl<'a> SoftBody<'a> {
    /// Creates an empty authored deformation definition.
    pub fn new(name: impl Into<Cow<'a, str>>) -> Self {
        Self {
            scope: Scope::default(),
            effects: Vec::new(),
            lumps: Vec::new(),
            riders: Vec::new(),
            name: name.into(),
            meshes: Values::default(),
            detail: 0,
            copy_all: false,
            chains_as_they_are: false,
            inside: Values::default(),
            blend: 0.,
            influences: 0,
            equal_shares: false,
            colliders: Vec::new(),
            drips: None,
        }
    }
    /// Adds an effect with a stable body-local identity.
    pub fn add_effect(&mut self, effect: SoftEffect<'a>) -> SoftEffectId {
        let id = self.scope.allocate();
        self.effects.push((id, effect));
        id
    }
    /// Adds a pivot with a stable body-local identity.
    pub fn add_lump(&mut self, lump: SoftLump) -> SoftLumpId {
        let id = self.scope.allocate();
        self.lumps.push((id, lump));
        id
    }
    /// Adds a rigid mesh portion with a stable body-local identity.
    pub fn add_rider(&mut self, rider: SoftPart) -> RiderId {
        let id = self.scope.allocate();
        self.riders.push((id, rider));
        id
    }
    /// Authored effects in evaluation order.
    pub fn effects(&self) -> impl ExactSizeIterator<Item = (SoftEffectId, &SoftEffect<'a>)> {
        self.effects.iter().map(|(id, value)| (*id, value))
    }
    /// Authored pivots in preparation order.
    pub fn lumps(&self) -> impl ExactSizeIterator<Item = (SoftLumpId, &SoftLump)> {
        self.lumps.iter().map(|(id, value)| (*id, value))
    }
    /// Rigid mesh portions in their authored order.
    pub fn riders(&self) -> impl ExactSizeIterator<Item = (RiderId, &SoftPart)> {
        self.riders.iter().map(|(id, value)| (*id, value))
    }
    /// Resolves an actual effect in this definition.
    pub fn effect(&self, id: SoftEffectId) -> Option<&SoftEffect<'a>> {
        self.effects
            .iter()
            .find_map(|(key, value)| (*key == id).then_some(value))
    }
    /// Resolves an actual pivot in this definition.
    pub fn lump(&self, id: SoftLumpId) -> Option<&SoftLump> {
        self.lumps
            .iter()
            .find_map(|(key, value)| (*key == id).then_some(value))
    }
    /// Resolves an actual rigid mesh portion in this definition.
    pub fn rider(&self, id: RiderId) -> Option<&SoftPart> {
        self.riders
            .iter()
            .find_map(|(key, value)| (*key == id).then_some(value))
    }
    /// Replaces one effect while preserving its identity and references.
    pub fn set_effect(&mut self, id: SoftEffectId, effect: SoftEffect<'a>) -> Result<(), Error> {
        let value = self
            .effects
            .iter_mut()
            .find(|(key, _)| *key == id)
            .ok_or_else(|| Error::new("wem.soft.effect", "effect belongs to another body"))?;
        value.1 = effect;
        Ok(())
    }
    /// Replaces one pivot while preserving its identity and references.
    pub fn set_lump(&mut self, id: SoftLumpId, lump: SoftLump) -> Result<(), Error> {
        let value = self
            .lumps
            .iter_mut()
            .find(|(key, _)| *key == id)
            .ok_or_else(|| Error::new("wem.soft.lump", "pivot belongs to another body"))?;
        value.1 = lump;
        Ok(())
    }
    /// Replaces one rigid mesh portion while preserving its identity and references.
    pub fn set_rider(&mut self, id: RiderId, rider: SoftPart) -> Result<(), Error> {
        let value = self
            .riders
            .iter_mut()
            .find(|(key, _)| *key == id)
            .ok_or_else(|| Error::new("wem.soft.rider", "rider belongs to another body"))?;
        value.1 = rider;
        Ok(())
    }
}
