//! Closed authored channel operations map by meaning, preserving unknown producer choices.
use crate::model::conversion::Error;
use crate::model::semantic::profiles::wem::animation::Operation;
use crate::model::wem::records::Channel;
pub(super) fn read(value: Channel) -> Result<Operation, Error> {
    Ok(match value {
        Channel::Translation => Operation::Translation,
        Channel::Rotation => Operation::Rotation,
        Channel::Scale => Operation::Scale,
        Channel::Visibility => Operation::Visibility,
        Channel::Color => Operation::Color,
        Channel::Alpha => Operation::Alpha,
        Channel::Intensity => Operation::Intensity,
        Channel::AttenuationStart => Operation::AttenuationStart,
        Channel::AttenuationEnd => Operation::AttenuationEnd,
        Channel::UvTranslate => Operation::UvTranslate,
        Channel::UvRotate => Operation::UvRotate,
        Channel::UvScale => Operation::UvScale,
        Channel::Weight => Operation::Weight,
        Channel::TextureIndex => Operation::TextureIndex,
        Channel::Emissive => Operation::Emissive,
        Channel::EmitterProperty => Operation::EmitterProperty,
        Channel::ShadowCastingStart => Operation::ShadowCastingStart,
        Channel::ShadowCastingEnd => Operation::ShadowCastingEnd,
        Channel::QuadraticFalloff => Operation::QuadraticFalloff,
        Channel::LinearFalloff => Operation::LinearFalloff,
        Channel::Damping => Operation::Damping,
        Channel::StageWeight => Operation::StageWeight,
        Channel::StageSourceWeight => Operation::StageSourceWeight,
        Channel::StageSourceEnabled => Operation::StageSourceEnabled,
        Channel::FocusDistance => Operation::FocusDistance,
        Channel::FocalLength => Operation::FocalLength,
        Channel::FStop => Operation::FStop,
        Channel::Target => Operation::Target,
        Channel::Roll => Operation::Roll,
        Channel::PhysicsDynamic => Operation::PhysicsDynamic,
        Channel::ClothActive => Operation::ClothActive,
        Channel::PhysicsRagdoll => Operation::PhysicsRagdoll,
        Channel::PhysicsBlend => Operation::PhysicsBlend,
        Channel::ClothDriverTranslation => Operation::ClothDriverTranslation,
        Channel::ClothDriverRotation => Operation::ClothDriverRotation,
        Channel::NormalTextureIndex => Operation::NormalTextureIndex,
        Channel::OrmTextureIndex => Operation::OrmTextureIndex,
        Channel::EmissiveTextureIndex => Operation::EmissiveTextureIndex,
        Channel::TeamColorTextureIndex => Operation::TeamColorTextureIndex,
        Channel::EnvironmentTextureIndex => Operation::EnvironmentTextureIndex,
        Channel::SoftAmount => Operation::SoftAmount,
        Channel::SoftLumpTranslation => Operation::SoftLumpTranslation,
        Channel::SoftLumpRotation => Operation::SoftLumpRotation,
        Channel::SoftLumpScale => Operation::SoftLumpScale,
        Channel::Unknown(value) => Operation::Unknown(value),
        Channel::Count => {
            return Err(Error::new(
                "wem.animation.operation",
                "sentinel does not declare an animated control",
            ));
        }
    })
}
