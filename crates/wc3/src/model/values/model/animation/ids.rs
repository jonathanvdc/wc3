//! External WoW animation-data categories.
//!
//! Catalog sources (snapshot 2026-10-18):
//! <https://wowdev.wiki/M2/AnimationList> and
//! <https://gist.github.com/Marlamin/91e5f37a1ba4d2276550525133095f5b>.
//! The catalog covers IDs 0 through 1577; client availability varies by version.

/// External WoW animation-data category shared by a sequence's variations.
///
/// This is independent of a model's clip indices. All `u16` values are preserved,
/// including categories introduced by newer clients or custom data. Named
/// constants identify documented categories without imposing client-version checks.
#[repr(transparent)]
#[derive(Clone, Copy, Debug, Default, Eq, Hash, Ord, PartialEq, PartialOrd)]
pub struct AnimationId(u16);

impl AnimationId {
    /// Creates a category without restricting it to known named values.
    pub const fn new(value: u16) -> Self {
        Self(value)
    }

    /// Returns the external animation-data category number.
    pub const fn get(self) -> u16 {
        self.0
    }
}

impl From<u16> for AnimationId {
    fn from(value: u16) -> Self {
        Self::new(value)
    }
}

impl From<AnimationId> for u16 {
    fn from(value: AnimationId) -> Self {
        value.get()
    }
}

macro_rules! animation_ids {
    ($($constant:ident = $id:literal => $name:literal,)*) => {
        impl AnimationId {
            $(
                #[doc = concat!("The `", $name, "` animation-data category.")]
                pub const $constant: Self = Self::new($id);
            )*

            /// Returns the documented native name, or `None` for an uncatalogued ID.
            ///
            /// Names retain native spelling, such as `Walk` and `FlyAttack1H`.
            /// A known name does not imply that a particular model contains this animation.
            pub const fn name(self) -> Option<&'static str> {
                match self.0 {
                    $($id => Some($name),)*
                    _ => None,
                }
            }
        }

        #[cfg(test)]
        const CATALOG: &[(AnimationId, &str)] = &[
            $((AnimationId::$constant, $name),)*
        ];
    };
}

